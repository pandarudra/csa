#!/usr/bin/env bash
# Reproduces the headline evaluation numbers end to end.
# See README.md "Reproducing Results" for the full walkthrough.
set -euo pipefail
cd "$(dirname "$0")/.."

echo "== SpotifyCares support agent: evaluation =="

if [ ! -f .env ]; then
  echo "ERROR: .env not found. Copy .env.example to .env and set NVIDIA_API_KEY." >&2
  exit 1
fi

if [ ! -d .venv ]; then
  echo "-- creating virtual environment --"
  python3 -m venv .venv
fi
# shellcheck disable=SC1091
source .venv/bin/activate
pip install -q -r requirements.txt

mkdir -p data/processed results

if [ ! -f data/processed/spotify_threads.jsonl ]; then
  echo "== step 1/4: preparing threads from the raw TWCS export =="
  python -m src.data_prep
else
  echo "== step 1/4: using cached data/processed/spotify_threads.jsonl =="
fi

if [ ! -f golden/golden_set.csv ]; then
  echo "ERROR: golden/golden_set.csv not found." >&2
  echo "Run 'python -m src.label_tool' first -- the golden set is hand-labeled and not regenerated by this script." >&2
  exit 1
fi

if [ ! -f data/processed/retrieval_index.npy ]; then
  echo "== step 2/4: building the retrieval index =="
  python -m src.retrieve
else
  echo "== step 2/4: using cached retrieval index =="
fi

echo "== step 3/4: running baselines + full agent + LLM judge over the golden test split =="
python -m src.eval_harness

echo "== step 4/4: headline metrics =="
python -c "import json; print(json.dumps(json.load(open('results/metrics.json')), indent=2))"

cat <<'EOF'

Done. Full outputs:
  results/metrics.json         -- accuracy/F1/escalation metrics for all 3 systems
  results/failure_cases.json   -- full-agent examples that disagreed with the golden label
  results/judge_results.jsonl  -- per-example LLM-judge reply-quality scores

Judge/human agreement evidence (needs a short interactive session, not run by default):
  python -m src.eval_harness --human-judge       # score a sample of the same replies yourself
  python -m src.eval_harness --judge-agreement   # compare your scores against the LLM judge's
EOF
